const LANGS = ["en", "hi", "te"];
function getLang() {
  const l = localStorage.getItem("lb_lang");
  return LANGS.includes(l) ? l : "en";
}
function setLang(l) {
  if (!LANGS.includes(l)) return;
  localStorage.setItem("lb_lang", l);
  document.dispatchEvent(new CustomEvent("lb:lang"));
}
function t(key) {
  const l = getLang();
  return (I18N[l] && I18N[l][key]) || I18N.en[key] || key;
}
function tf(key, vars) {
  let s = t(key);
  for (const k in (vars || {})) s = s.replace("{" + k + "}", vars[k]);
  return s;
}
function pick(obj) {
  if (obj == null) return "";
  if (typeof obj === "string") return obj;
  return obj[getLang()] || obj.en || "";
}
function applyStaticI18n(root) {
  (root || document).querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
}
